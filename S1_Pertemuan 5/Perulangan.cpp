#include <iostream>
using namespace std;

int main() 
{
    cout << "Contoh Program perulangan\n";
    for (int i = 1; i <= 10; i++) {
        cout << i << endl;
    }

    cout << endl; 

    cout << "Perulangan menurun\n";
    for (int j = 10; j >= 1; j--) {
        cout << j << endl;
    }

    return 0;
}